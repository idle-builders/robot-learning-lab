"""Regenerate or clean disposable scratch files for the Complete Cove-50 FDM Ape Body Study (`cove50-complete-fdm-body-r1`)."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[3]
STUDY_DIR = Path(__file__).resolve().parent
ART_DIR = ROOT / "artifacts/robot/body/assembly"


def clean_scratch() -> None:
    removed: list[str] = []
    exe_bin = ART_DIR / "zbuffer_renderer_bin"
    if exe_bin.exists():
        removed.append(str(exe_bin.relative_to(ROOT)))
        exe_bin.unlink()

    scratch_dir = ART_DIR / "scratch_stl"
    if scratch_dir.exists():
        for p in sorted(scratch_dir.rglob("*.stl")):
            removed.append(str(p.relative_to(ROOT)))
            p.unlink()
        shutil.rmtree(scratch_dir, ignore_errors=True)

    reg_record = {
        "schema": "cove50.scratch_regeneration.v1",
        "study": "robot/body/assembly",
        "regenerate_command": ".venv/bin/python robot/body/assembly/regenerate_derived.py --regenerate",
        "clean_command": ".venv/bin/python robot/body/assembly/regenerate_derived.py --clean",
        "cleaned_disposable_files": removed,
    }
    (STUDY_DIR / "scratch-regeneration.json").write_text(json.dumps(reg_record, indent=2) + "\n")
    print(f"Cleaned {len(removed)} disposable scratch files and recorded scratch-regeneration.json")


def regenerate() -> None:
    py = str(ROOT / ".venv/bin/python")
    subprocess.run([py, str(STUDY_DIR / "assemble_complete_fdm_body.py")], check=True)
    # the study record is generated by robot/body/bom/publish_body.py (from the body definitions); publish it from main with --publish


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--clean", action="store_true")
    ap.add_argument("--regenerate", action="store_true")
    args = ap.parse_args()
    if args.regenerate:
        regenerate()
    if args.clean:
        clean_scratch()


if __name__ == "__main__":
    main()
