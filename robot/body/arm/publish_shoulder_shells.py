"""Publish the parametric shoulder shells (Idle T-tph7xb) on the robot design dashboard: a thin wrapper.

The record is generated by the generic body publisher (robot/body/bom/publish_body.py, T-zmmdkm) from the `study` block in
robot/body/arm/shoulder_shells.bom.yaml (title, sections, observation, measurements, limitations, renders, evidence), the
selected manifest, the body definitions and the check reports; the CAD is the generic display GLB of the selected body.
Edit the study block, not this file.

  .venv/bin/python -B robot/body/arm/publish_shoulder_shells.py            # = publish_body.py --study shoulder-shells-parametric (record to a file)
  .venv/bin/python -B robot/body/arm/publish_shoulder_shells.py --publish  # main checkout: package the GLB if stale, then publish
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]

if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if a not in ("record", "package")]   # the old subcommands are covered by publish_body.py
    sys.exit(subprocess.run([sys.executable, "-B", "robot/body/bom/publish_body.py", "--study", "shoulder-shells-parametric", *args], cwd=ROOT).returncode)
