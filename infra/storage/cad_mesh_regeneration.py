"""Recreate registered CAD inspection/print exports from exact retained mesh inputs.

No remeshing, contact solve, CAD Boolean or controller execution. Native observations
are never regenerated by this adapter. Recipe and source geometry hashes are checked.
"""
from pathlib import Path
import json,hashlib,os,io,struct,tempfile,subprocess,zipfile
from concurrent.futures import ThreadPoolExecutor
ROOT=Path(__file__).resolve().parents[2]

def digest(b):return hashlib.sha256(b).hexdigest()
def load_scene(record):
 from infra.storage.transient_assets import materialized_input
 with materialized_input(ROOT/record['scene_manifest'])as path:
  data=path.read_bytes()
  if digest(data)!=record['scene_sha256']:raise ValueError('CAD scene definition differs')
  return json.loads(data)

def meshes(scene,names=None):
 import numpy as np,trimesh
 from infra.storage.transient_assets import materialized_input
 selected=[p for p in scene['parts']if names is None or p['name']in names]
 def read(p):
  with materialized_input(ROOT/p['input']['path'])as path:
   if digest(path.read_bytes())!=p['input']['sha256']:raise ValueError('CAD mesh input differs '+p['name'])
   with np.load(path,allow_pickle=False)as d:m=trimesh.Trimesh(d['vertices'],d['faces'],process=False)
  return p['name'],m
 with ThreadPoolExecutor(max_workers=8)as pool:return dict(pool.map(read,selected))

def transforms(joints,q):
 import numpy as np
 from scipy.spatial.transform import Rotation
 T={'torso':np.eye(4)};todo=list(joints)
 while todo:
  count=len(todo)
  for j in todo[:]:
   if j['parent']not in T:continue
   R=Rotation.from_rotvec(np.asarray(j['axis_world_neutral'])*np.deg2rad(q.get(j['name'],0))).as_matrix();p=np.array(j['origin_world_mm']);a=np.eye(4);a[:3,:3]=R;a[:3,3]=p-R@p;T[j['child']]=T[j['parent']]@a;todo.remove(j)
  if count==len(todo):raise ValueError('CAD inspection joint graph disconnected')
 return T

def posed(scene,geometry,q,hide=False):
 T=transforms(scene['joints'],q);out=[]
 for p in scene['parts']:
  if hide and p['role']=='hard_cover':continue
  m=geometry[p['name']].copy();m.apply_transform(T[p['owning_link']]);out.append((p['name'],m,p['color']))
 return out

def raster(items,view,box,work,W,H):
 import numpy as np
 from PIL import Image
 cpp=ROOT/'robot/electronics/power/cad/zbuffer_renderer.cpp';exe=work/'renderer'
 if not exe.exists():subprocess.run(['clang++','-std=c++17','-O3',str(cpp),'-o',str(exe)],check=True)
 view=np.array(view,float);view/=np.linalg.norm(view);right=np.cross([0,0,1],view);right/=np.linalg.norm(right);up=np.cross(view,right);tris=[];colors=[]
 for n,m,c in items:
  tris.append(m.triangles);colors.append(np.array(c[:3])/255*(.68+.32*np.abs(m.face_normals@np.array([.3,-.5,.8])))[:,None])
 tri=np.concatenate(tris);col=np.concatenate(colors);xy=np.stack([tri@right,tri@up],axis=-1)
 import trimesh
 pts=trimesh.bounds.corners(np.asarray(box));proj=np.stack([pts@right,pts@up],axis=-1);lo=proj.min(0);hi=proj.max(0);scale=min(W/(hi[0]-lo[0]),H/(hi[1]-lo[1]))*.90;mid=(lo+hi)/2;xyz=np.empty_like(tri);xyz[:,:,0]=(xy[:,:,0]-mid[0])*scale+W/2;xyz[:,:,1]=H/2-(xy[:,:,1]-mid[1])*scale;xyz[:,:,2]=tri@view;data=np.concatenate([xyz.reshape(-1,9),col],axis=1).astype('<f4');target=work/'frame.ppm'
 subprocess.run([str(exe),'/dev/stdin',str(target)],input=struct.pack('<III',W,H,len(tri))+data.tobytes(),check=True)
 return Image.open(target).copy()

def stl(scene,geom,name):
 import numpy as np,trimesh
 p=next(p for p in scene['parts']if p['name']==name);m=geom[name].copy();m.apply_transform(np.array(p['print_transform_mm']));return m.export(file_type='stl')

def encode(scene,key,work):
 import trimesh
 output=scene['outputs'][key];kind=output['format'];names=[output['part']]if kind in ['ply','stl']else None;geom=meshes(scene,names)
 if kind=='ply':return geom[output['part']].export(file_type='ply')
 if kind=='stl':return stl(scene,geom,output['part'])
 if kind=='glb':
  s=trimesh.Scene()
  for n,m,c in posed(scene,geom,output.get('q',{}),output.get('hide',False)):
   m.apply_scale(.001);m.visual.face_colors=c;s.add_geometry(m,node_name=n,geom_name=n)
  return s.export(file_type='glb')
 if kind=='png':
  from PIL import Image,ImageDraw
  views=output['views'];w,h=output.get('tile_size',[480,610]);canvas=Image.new('RGB',(w*len(views),h+35),'#f3f1eb');draw=ImageDraw.Draw(canvas)
  for i,v in enumerate(views):
   canvas.paste(raster(posed(scene,geom,v.get('q',{}),v.get('hide',False)),v['direction'],output['box'],work,w,h),(w*i,35));draw.text((w*i+12,12),v['label'],fill='#252b30')
  buf=io.BytesIO();canvas.save(buf,format='PNG');return buf.getvalue()
 if kind=='zip':
  buf=io.BytesIO()
  with zipfile.ZipFile(buf,'w',zipfile.ZIP_DEFLATED)as z:
   for p in scene['parts']:
    if 'print_transform_mm'in p:
     zi=zipfile.ZipInfo(p['name']+'.stl',(2026,10,30,0,0,0));zi.compress_type=zipfile.ZIP_DEFLATED;z.writestr(zi,stl(scene,geom,p['name']))
   zi=zipfile.ZipInfo('ASSEMBLY.md',(2026,10,30,0,0,0));zi.compress_type=zipfile.ZIP_DEFLATED;z.writestr(zi,scene['assembly_notes'])
  return buf.getvalue()
 raise ValueError('Unknown CAD inspection format')

def rebuild(record,destination):
 if digest(Path(__file__).read_bytes())!=record['regenerator_sha256']:raise ValueError('CAD exporter source changed')
 cpp=ROOT/'robot/electronics/power/cad/zbuffer_renderer.cpp'
 if digest(cpp.read_bytes())!=record['renderer_sha256']:raise ValueError('CAD raster source changed')
 scene=load_scene(record);destination=Path(destination);destination.parent.mkdir(parents=True,exist_ok=True)
 with tempfile.TemporaryDirectory(prefix='cad-export-',dir=ROOT/'.cache')as scratch:
  data=encode(scene,record['output_key'],Path(scratch))
  if len(data)!=record['bytes']or digest(data)!=record['sha256']:raise ValueError('Recreated CAD export differs')
  temporary=Path(scratch)/destination.name;temporary.write_bytes(data)
  if destination.exists():raise FileExistsError(destination)
  # Request destinations are on the same local checkout; use a verified copy.
  with destination.open('xb')as stream:stream.write(data)
 return destination
