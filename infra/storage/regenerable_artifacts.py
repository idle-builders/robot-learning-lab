"""Recreate explicitly registered disposable exports from retained native inputs."""

import argparse
import fcntl
import json
import os
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "data/regenerable-artifacts.json"


def lookup(path):
    path = Path(path)
    if not path.is_absolute():
        path = ROOT / path
    try:
        name = path.relative_to(ROOT).as_posix()
    except ValueError:
        return None
    if not REGISTRY.exists():
        return None
    return json.loads(REGISTRY.read_text())["files"].get(name)


def rebuild(record, destination):
    """Recombine fields without remeshing or solving a stiffness system."""
    if record["kind"] == "cad-mesh-export.v1":
        from infra.storage.cad_mesh_regeneration import rebuild as rebuild_cad
        return rebuild_cad(record, destination)
    if record["kind"] == "gsplat-ply.v1":
        return rebuild_ply(record, destination)
    if record["kind"] == "trimesh-graft-glb.v1":
        from infra.storage.glb_regeneration import rebuild as rebuild_glb
        return rebuild_glb(record, destination)
    import numpy as np
    from infra.storage import blob_store

    if record["kind"] != "fem-case-fields.v1":
        raise ValueError("Unknown regeneration recipe")
    from contextlib import ExitStack
    from infra.storage.transient_assets import materialized_input
    with ExitStack() as stack:
        inputs = []
        for key, digest_key in [("canonical_unit_fields", "unit_fields_sha256"),
                                ("case_coefficients_report", "report_sha256")]:
            path = stack.enter_context(materialized_input(blob_store.safe_path(record[key])))
            if blob_store.digest(path) != record[digest_key]:
                raise ValueError(f"Regeneration input changed: {record[key]}")
            inputs.append(path)
        return rebuild_fem(record, destination, inputs)


def rebuild_fem(record, destination, inputs):
    import numpy as np
    from infra.storage import blob_store
    report = json.loads(inputs[1].read_text())
    energy_fields = "/stance-loads-r2/" in record["path"]
    fields = {}
    with np.load(inputs[0], allow_pickle=False) as basis:
        displacement = basis["displacement_mm"]
        unit_stress = basis["stress_MPa"]
        for case in report["cases"]:
            target = np.asarray(case["target_wrench_N_Nmm"])
            if energy_fields:
                u = np.einsum("nki,i->nk", displacement, target)
            else:
                u = (displacement.reshape(-1, 6) @ target).reshape(-1, 3)
            stress = np.einsum("i,iea->ea", target, unit_stress)
            sx, sy, sz, txy, tyz, txz = stress.T
            von = np.sqrt(((sx-sy)**2 + (sy-sz)**2 + (sz-sx)**2) / 2
                          + 3 * (txy*txy + tyz*tyz + txz*txz))
            prefix = case["case_id"] + "__"
            fields[prefix + "displacement_mm"] = u
            fields[prefix + "stress_MPa"] = stress
            fields[prefix + "von_mises_MPa"] = von
            if energy_fields:
                strain = np.einsum("i,iea->ea", target, basis["strain"])
                volume = basis["tetra_volume_mm3"]
                energy = .5 * np.sum(stress * strain, axis=1) * volume
                fields[prefix + "strain_energy_density_MPa"] = energy / volume
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(dir=destination.parent, suffix=".npz",
                                         delete=False) as stream:
            temporary = Path(stream.name)
            np.savez_compressed(stream, **fields)
        if (temporary.stat().st_size != record["bytes"]
                or blob_store.digest(temporary) != record["sha256"]):
            raise ValueError("Regenerated bytes differ; use the recorded NumPy/zlib runtime")
        if destination.exists():
            raise FileExistsError(destination)
        os.replace(temporary, destination)
        temporary = None
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)
    return destination


def rebuild_ply(record, destination):
    """Export an exact retained Gaussian checkpoint on CPU, without retraining."""
    import subprocess
    from infra.storage import blob_store

    for name, expected in record["source_hashes"].items():
        source = ROOT / name
        if not source.resolve().is_relative_to(ROOT) or blob_store.digest(source) != expected:
            raise ValueError("PLY exporter source changed")
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    checkpoint = blob_store.safe_path(record["checkpoint_path"])
    # A temporary input keeps an on-demand view from leaving a large checkpoint local.
    with tempfile.TemporaryDirectory(prefix="ply-input-", dir=ROOT / ".cache") as scratch:
        if not checkpoint.is_file():
            row = blob_store.lookup(checkpoint)
            if row is None or row["sha256"] != record["checkpoint_sha256"]:
                raise ValueError("PLY checkpoint archive differs")
            checkpoint = restore_packed_input(row, Path(scratch))
        before = blob_store.identity(checkpoint.stat())
        if blob_store.digest(checkpoint) != record["checkpoint_sha256"]:
            raise ValueError("PLY checkpoint changed")
        temporary = None
        try:
            with tempfile.NamedTemporaryFile(dir=destination.parent, suffix=".ply", delete=False) as stream:
                temporary = Path(stream.name)
            subprocess.run([str(ROOT / ".venv-control/bin/python"), "-B",
                            str(ROOT / record["exporter_script"]), str(checkpoint), str(temporary)],
                           check=True, timeout=180, cwd=ROOT)
            if (temporary.stat().st_size != record["bytes"]
                    or blob_store.digest(temporary) != record["sha256"]
                    or blob_store.identity(checkpoint.stat()) != before):
                raise ValueError("Regenerated PLY or its checkpoint differs")
            os.link(temporary, destination)
            return destination
        finally:
            if temporary is not None:
                temporary.unlink(missing_ok=True)


def restore_packed_input(row, scratch):
    """Restore a temporary packed input with bounded downloads and exact original hashes."""
    import sqlite3
    from boto3.s3.transfer import TransferConfig
    from infra.storage import blob_store

    with sqlite3.connect(f"file:{blob_store.INDEX}?mode=ro", uri=True) as db:
        pack_hash, pack_bytes = db.execute("SELECT sha256,bytes FROM packs WHERE key=?",
                                          (row["pack_key"],)).fetchone()
    pack = scratch / "pack"
    blob_store.client().download_file(
        blob_store.BUCKET, row["pack_key"], str(pack),
        Config=TransferConfig(max_concurrency=4, multipart_chunksize=16 << 20))
    if pack.stat().st_size != pack_bytes or blob_store.digest(pack) != pack_hash:
        raise ValueError("Checkpoint pack full hash differs")

    class LocalRange:
        def get_object(self, **request):
            if request["Key"] != row["pack_key"] or request["Bucket"] != blob_store.BUCKET:
                raise ValueError("Unexpected checkpoint range")
            expected = f"bytes={row['offset']}-{row['offset'] + row['stored_bytes'] - 1}"
            if request["Range"] != expected:
                raise ValueError("Unexpected checkpoint range")
            # The decoder consumes exactly the compressed member. No whole-pack copy in RAM.
            class Body:
                def __init__(self):
                    self.file = pack.open("rb")
                    self.file.seek(row["offset"])
                    self.remaining = row["stored_bytes"]
                def read(self, count):
                    data = self.file.read(min(count, self.remaining))
                    self.remaining -= len(data)
                    return data
                def close(self):
                    self.file.close()
            return {"ContentLength": row["stored_bytes"], "Body": Body()}
    return blob_store.restore_entry(row, LocalRange(), scratch / "checkpoint.pt")


def regenerate(path):
    record = lookup(path)
    if record is None:
        raise ValueError("No verified regeneration recipe for this path")
    from infra.storage import blob_store
    destination = blob_store.safe_path(record["path"])
    lock = ROOT / ".cache/derived-artifact.lock"
    lock.parent.mkdir(exist_ok=True)
    with lock.open("a") as stream:
        fcntl.flock(stream, fcntl.LOCK_EX)
        if destination.is_file():
            if blob_store.digest(destination) != record["sha256"]:
                raise ValueError("Existing generated file differs")
            return destination
        return rebuild(record, destination)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path")
    parser.add_argument("--output", type=Path, help="Write a working copy under .cache or another explicit destination")
    args = parser.parse_args()
    if args.output:
        record = lookup(args.path)
        if record is None:
            raise ValueError("No verified regeneration recipe for this path")
        if args.output.exists():
            raise FileExistsError(args.output)
        print(rebuild(record, args.output))
    else:
        print(regenerate(args.path))
