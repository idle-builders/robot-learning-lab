"""Render restored WBC pilot episodes and print the dashboard matrix.

Each clip shows R3 panels side by side from native traces: the kinematic
reference, open-loop reference playback through the servos, and one panel per
evaluated controller (--arm LABEL=EVALUATE_DIR, the first arm chooses the
worlds). All arms share world draws and pushes, so world i is the same start
in every panel. Clips go to --work (cheap, regenerated by this command from the
retained traces); the dashboard keeps the verified private copies.

    .venv-control/bin/python control/wbc/compute/report.py \
      --evidence artifacts/runs/RUN --motion MOTION.npz --work DIR \
      [--arm 'WBC teacher=evaluate' ...] [--publish RECORD.json]
"""
import argparse
import json
from pathlib import Path
import subprocess

import imageio.v2 as imageio
import mujoco
import numpy as np
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[3]
XML = ROOT / 'artifacts/robot/model/timestep/cove50-rigid.xml'


def frames(model, data, renderer, camera, qpos, label, size):
    out = []
    for q in qpos:
        data.qpos[:] = q
        mujoco.mj_forward(model, data)
        camera.lookat[:] = data.qpos[:3] - [0, 0, .08]
        renderer.update_scene(data, camera)
        image = Image.fromarray(renderer.render())
        ImageDraw.Draw(image).text((8, 8), label, fill=(235, 235, 235))
        out.append(np.asarray(image))
    return out


def clip(path, panels, note, model=None):
    """panels: [(label, qpos [T,29])]; the first is the reference. model: a compiled scene to draw instead of the R3
    rigid MJCF (a scaled body, e.g. the ape body's longer arms), with the same qpos layout."""
    # Each world sits at its own grid origin; move it to the reference origin
    # so all panels share the scene lighting.
    reference = panels[0][1]
    shifted = []
    for label, q in panels:
        q = q.copy()
        q[:, :2] -= q[0, :2] - reference[0, :2]
        shifted.append((label, q))
    size = 360 if len(panels) <= 3 else 296  # multiples of the codec's 8-pixel blocks
    model = model or mujoco.MjModel.from_xml_path(str(XML))
    data = mujoco.MjData(model)
    camera = mujoco.MjvCamera()
    camera.distance, camera.elevation, camera.azimuth = 1.2, -12, 135
    with mujoco.Renderer(model, size, size) as renderer:
        rendered = [frames(model, data, renderer, camera, q, label, size) for label, q in shifted]
    with imageio.get_writer(path, fps=50, codec='libx264', quality=7, macro_block_size=8) as writer:
        for t, row in enumerate(zip(*rendered)):
            image = Image.fromarray(np.concatenate(row, axis=1))
            ImageDraw.Draw(image).text((8, size - 20), f'{note}  t={t / 50:.2f} s', fill=(235, 235, 235))
            writer.append_data(np.asarray(image))


def reference_qpos(motion, steps):
    m = np.load(motion)
    # Trace row t is the state after step t, i.e. reference frame t + 1.
    return np.concatenate((m['body_pos_w'][1:steps + 1, 0], m['body_quat_w'][1:steps + 1, 0], m['joint_pos'][1:steps + 1]), axis=1)


def survival(report, steps):
    """Seconds clear of the native termination conditions, per condition (a full episode counts as its length)."""
    return {r['condition']: np.array([s if s is not None else steps / 50 for s in r['native_termination_condition']['first_flag_s']])
        for r in report['rows'] if r['mode'] == 'teacher'}


def path_error(trace):
    """Per-world final root xy error to the clip path [m].

    Uses the row before the last: reports before 2026-11-03 compared the last
    row, where the motion command has already wrapped to the clip start.
    """
    return np.linalg.norm(trace['qpos'][-2, :, :2] - trace['ref_anchor_pos'][-2, :, :2], axis=1)


def root_path(trace):
    """Median final root xy error to the clip path and travel from the start [m]."""
    return (round(float(np.median(path_error(trace))), 3),
        round(float(np.median(np.linalg.norm(trace['qpos'][-2, :, :2] - trace['qpos'][0, :, :2], axis=1))), 3))


def gait(trace):
    """Median foot lifts (R, L) and heading change [deg], robot and clip.

    A lift is a rise of the foot more than 1 cm above its own 10th-percentile
    height. The last row is skipped: the motion command has wrapped to the start.
    """
    def lifts(z):
        up = (z - np.percentile(z, 10, axis=0)) > .01
        return np.median((np.diff(up.astype(int), axis=0) == 1).sum(0), axis=0).tolist()

    def heading(q):
        yaw = np.unwrap(np.arctan2(2 * (q[..., 0] * q[..., 3] + q[..., 1] * q[..., 2]), 1 - 2 * (q[..., 2] ** 2 + q[..., 3] ** 2)), axis=0)
        return round(float(np.degrees(np.median(yaw[-1] - yaw[0]))), 1)
    return dict(foot_lifts_p50=lifts(trace['end_z'][:-1, :, :2]), clip_foot_lifts_p50=lifts(trace['ref_end_z'][:-1, :, :2]),
        heading_change_deg_p50=heading(trace['qpos'][:-1, :, 3:7]), clip_heading_change_deg_p50=heading(trace['ref_anchor_quat'][:-1]))


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--evidence', type=Path, required=True)
    parser.add_argument('--motion', type=Path, required=True)
    parser.add_argument('--work', type=Path, required=True)
    parser.add_argument('--arm', action='append', help='LABEL=EVALUATE_DIR under evidence/ (default: WBC teacher=evaluate)')
    parser.add_argument('--publish', type=Path, help='dashboard record template; clips keyed by condition/kind')
    args = parser.parse_args()
    arms = [a.split('=', 1) for a in (args.arm or ['WBC teacher=evaluate'])]
    reports = {label: json.loads((args.evidence / 'evidence' / d / 'report.json').read_text()) for label, d in arms}
    traces = {label: {(r['condition'], r['mode']): np.load(args.evidence / 'evidence' / d / r['trace']) for r in reports[label]['rows']}
        for label, d in arms}
    args.work.mkdir(parents=True, exist_ok=True)
    primary = arms[0][0]
    steps = traces[primary]['nominal', 'teacher']['qpos'].shape[0]
    reference = reference_qpos(args.motion, steps)
    alive = survival(reports[primary], steps)
    kick = traces[primary]['pushed', 'teacher']['push_velocity_xy']
    # Shortest clear first; when worlds tie (all clear), the larger path error goes first.
    order = {c: np.lexsort((-path_error(traces[primary][c, 'teacher']), alive[c])) for c in alive}
    best = np.lexsort((-np.linalg.norm(kick, axis=1), -alive['pushed']))[0]  # longest clear, strongest push
    picks = [('nominal', int(order['nominal'][len(order['nominal']) // 2]), 'representative'),
        ('nominal', int(order['nominal'][0]), 'severe'),
        ('pushed', int(best), 'best'), ('pushed', int(order['pushed'][0]), 'severe')]
    clips = []
    for condition, world, kind in picks:
        name = f'{condition}-{kind}-w{world:02d}.mp4'
        speed = float(np.linalg.norm(kick[world])) if condition == 'pushed' else 0.
        push_s = next(r['push_step'] for r in reports[primary]['rows'] if r['condition'] == 'pushed')
        note = f'{condition}, world {world}' + (f', push {speed:.2f} m/s at t={push_s / 50:.1f} s' if speed else '')
        panels = [('Reference motion', reference), ('Servo playback (no WBC)', traces[primary][condition, 'reference']['qpos'][:, world])]
        panels += [(label, traces[label][condition, 'teacher']['qpos'][:, world]) for label, _ in arms]
        clip(args.work / name, panels, note)
        clips.append(dict(file=name, condition=condition, world=world, kind=kind, push_m_s=speed,
            seconds_clear={label: float(survival(reports[label], steps)[condition][world]) for label, _ in arms}))
        print(name, flush=True)
    matrix = []
    for label, _ in arms:
        for r in reports[label]['rows']:
            if r['mode'] == 'reference' and label != primary:
                continue  # servo playback is identical across arms
            flags = r['native_termination_condition']
            first = [s for s in flags['first_flag_s'] if s is not None]
            clear = survival(dict(rows=[dict(r, mode='teacher')]), steps)[r['condition']]
            error, travel = root_path(traces[label][r['condition'], r['mode']])
            matrix.append(dict(arm='servo playback' if r['mode'] == 'reference' else label, condition=r['condition'],
                worlds=r['worlds'], joint_error_rad_p50=round(r['joint_abs_error_rad']['per_world_mean']['50'], 4),
                joint_error_rad_p90=round(r['joint_abs_error_rad']['per_world_mean']['90'], 4),
                worlds_reaching_termination_condition=flags['worlds_flagged'],
                first_condition_s_p50=round(float(np.median(first)), 2) if first else None,
                seconds_clear_p10_p50_p90=[round(float(np.percentile(clear, p)), 2) for p in (10, 50, 90)],
                lowest_torso_vs_reference_m=round(r['anchor_height_error_m']['min'], 3),
                final_root_xy_error_m_p50=error, root_travel_m_p50=travel,
                **gait(traces[label][r['condition'], r['mode']]),
                peak_abs_torque_Nm=round(r['peak_abs_torque_Nm'], 3),
                saturated_actuator_fraction=round(r['saturated_actuator_fraction'], 3)))
    (args.work / 'clips.json').write_text(json.dumps(dict(clips=clips, matrix=matrix), indent=2) + '\n')
    print(json.dumps(matrix, indent=1))
    if args.publish:
        publish(args, clips, matrix)


def publish(args, clips, matrix):
    """Fill rendered clip paths and the matrix into the record, then publish and upload it."""
    record = json.loads(args.publish.read_text())
    rendered = {(c['condition'], c['kind']): c for c in clips}
    for clip_row in record['clips']:
        made = rendered[clip_row.pop('condition'), clip_row.pop('kind')]
        clip_row['source_path'] = str((args.work / made['file']).resolve().relative_to(ROOT))
    record.setdefault('matrix', matrix)
    filled = args.work / 'record.json'
    filled.write_text(json.dumps(record, indent=2) + '\n')
    hub = [str(ROOT / '.venv/bin/python'), str(ROOT / 'infra/dashboard/results_hub.py')]
    subprocess.run([*hub, 'publish', str(filled)], cwd=ROOT, check=True)
    subprocess.run([*hub, 'upload', '--result-id', record['id']], cwd=ROOT, check=True)


if __name__ == '__main__':
    main()
