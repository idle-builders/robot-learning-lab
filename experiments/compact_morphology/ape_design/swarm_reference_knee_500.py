"""500 mm source-shell knee scale check with the *unchanged* ST3250 and 688s.

Run from repository root:
  .venv/bin/python experiments/compact_morphology/ape_design/swarm_reference_knee_500.py

This is a raw fit/motion comparison, not a relieved/printable joint. The shell
is regenerated by the independent design study at 500 mm; the motor and bearing
envelopes retain their 350 mm absolute dimensions.
"""

from __future__ import annotations

import json
from pathlib import Path

import build123d as bd
import numpy as np
import trimesh

from swarm_reference_knee_v2 import colored, cyl_x, box_at, volume


ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "artifacts/swarm-reference-knee-500-20261004"
STUDY = ROOT / "artifacts/sketch-ape-shell/exports/500mm/ape_shell_assembly.step"
SCALE = 500 / 350
AXIS = (42*SCALE, 3*SCALE + 10, 86*SCALE + 9)
ANGLES = tuple(range(0, 121, 10))
VIEW_ANGLES = (0, 30, 60, 90, 120)


def flex(shape, angle):
    return bd.Pos(*AXIS) * bd.Rot(angle, 0, 0) * bd.Pos(*(-v for v in AXIS)) * shape


def inner_thigh():
    # Same dimensioned stations as experiments/sketch_ape_shell/build.py;
    # 2 mm wall remains absolute after the design's 500 mm regeneration.
    stations = ((87,42,3,16,18),(98,43,3,20,22),(124,39,3,24,25),
                (145,35,4,22,23),(157,33,4,16,18),(163,31,4,8,10))
    return bd.Solid.make_loft([
        bd.Wire.make_ellipse(rx*SCALE-2, ry*SCALE-2,
                             bd.Plane(origin=(x*SCALE,y*SCALE,z*SCALE)))
        for z,x,y,rx,ry in stations
    ])


def bounds(part):
    bb = part.bounding_box()
    return [[round(v, 2) for v in bb.min], [round(v, 2) for v in bb.max]]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    p = {part.label: part for part in bd.import_step(STUDY).children}
    thigh = p["R_thigh_front"].fuse(p["R_thigh_back"])
    shin = p["R_shin_front"].fuse(p["R_shin_back"])
    cuff = p["R_knee_cuff"]
    foot = p["R_foot_dorsal"].fuse(
        p["R_toe_1"],p["R_toe_2"],p["R_toe_3"],p["R_sole"])
    motor = box_at((AXIS[0], AXIS[1]-12.2, AXIS[2]), (35,45.22,24.72))
    bearing_envelopes = [cyl_x(8,a,a+5,AXIS[1],AXIS[2])-
                         cyl_x(4.1,a-1,a+6,AXIS[1],AXIS[2])
                         for a in (36.5,78.5)]
    bearing_housings = [cyl_x(11.5,a,a+6,AXIS[1],AXIS[2])-
                        cyl_x(8.1,a-1,a+7,AXIS[1],AXIS[2])
                        for a in (36,78)]

    raw = []
    for angle in ANGLES:
        moved = flex(shin, angle)
        moved_foot = flex(foot, angle)
        raw.append({
            "flex_deg": angle,
            "shin_vs_unmodified_thigh_mm3": round(volume(moved.intersect(thigh)), 3),
            "shin_vs_motor_mm3": round(volume(moved.intersect(motor)), 3),
            "shin_vs_original_cosmetic_cuff_mm3": round(volume(moved.intersect(cuff)), 3),
            "shin_vs_bearing_housings_mm3": round(sum(volume(moved.intersect(h))
                                                       for h in bearing_housings), 3),
            "foot_vs_thigh_mm3": round(volume(moved_foot.intersect(thigh)), 3),
        })
        if angle not in VIEW_ANGLES:
            continue
        scene = trimesh.Scene()
        colored(scene,"exact_500mm_sketch_thigh",thigh,(225,217,202,255))
        colored(scene,"exact_500mm_sketch_shin",moved,(239,231,213,255))
        colored(scene,"exact_500mm_sketch_foot",moved_foot,(218,208,189,255))
        colored(scene,"original_cosmetic_knee_cuff",cuff,(105,101,95,190))
        colored(scene,"unchanged_ST3250_case",motor,(75,107,134,170))
        for i,housing in enumerate(bearing_housings):
            colored(scene,f"unchanged_688_housing_envelope_{i}",housing,
                    (91,92,89,220))
        scene.export(OUT / f"knee-{angle:03d}.glb")

    cavity = inner_thigh()
    cuff_cavity = bd.Solid.make_sphere(1).scale(
        (15*SCALE-2, 17*SCALE-2, 7*SCALE-2)).translate(
            (42*SCALE, 3*SCALE, 86*SCALE))
    joined_nominal_cavities = cavity.fuse(cuff_cavity)
    report = {
        "stage": "500 mm new-shell scale check, raw geometry only",
        "source_shell_step": str(STUDY.relative_to(ROOT)),
        "source_shell_height_mm": 500,
        "same_motor_and_bearings_as_350mm_coupon": True,
        "axis_mm_xyz": [round(v,3) for v in AXIS],
        "axis_relative_to_visual_cuff": "10 mm posterior, 9 mm above scaled cuff centre, as in 350 mm direct-drive packaging",
        "source_motor": "Feetech ST3250-C001; 35 x 45.22 x 24.72 mm oriented lateral/fore-aft/vertical; 12.2 mm output offset along Y; 74.5 g; 1.569 Nm rated at 12 V",
        "source_motor_url": "https://www.feetechrc.com/en/562636.html",
        "original_350mm_cuff_lateral_width_mm": 30.0,
        "scaled_500mm_cuff_lateral_width_mm": round(bounds(cuff)[1][0]-bounds(cuff)[0][0],2),
        "cuff_bounds_mm": bounds(cuff),
        "motor_bounds_mm": bounds(motor),
        "support_housing_bounds_mm": [bounds(h) for h in bearing_housings],
        "motor_inside_regenerated_nominal_thigh_cavity_pct": round(
            100*volume(motor.intersect(cavity))/motor.volume,2),
        "motor_inside_nominal_thigh_plus_cosmetic_cuff_cavity_pct": round(
            100*volume(motor.intersect(joined_nominal_cavities))/motor.volume,2),
        "motor_vs_unmodified_thigh_skin_mm3": round(volume(motor.intersect(thigh)),2),
        "motor_vs_cosmetic_cuff_mm3": round(volume(motor.intersect(cuff)),2),
        "raw_unmodified_poses": raw,
        "verdict": "SCALE IMPROVES FIT BUT DOES NOT PASS: 6.75 percent of motor remains outside joined nominal thigh+cuff cavities, motor occupies the cosmetic cuff skin, and unmodified thigh/shin and motor collide during flex",
        "limitations": [
            "No swept relief, moving yoke, positive running gap, fasteners or compliant cover is modeled in this scale check.",
            "Original cosmetic cuff is static; its collisions do not prove it can be a moving sleeve.",
            "Bearing housings are unchanged source-size envelopes, without a rated load path.",
            "At 500 mm, total robot mass, actuator thermal/torque margin, inertia, battery and learned policy transfer are unknown. Larger geometry does not establish control feasibility.",
        ],
    }
    (OUT / "report.json").write_text(json.dumps(report,indent=2)+"\n")
    (OUT / "index.html").write_text(
        Path(__file__).with_name("swarm_reference_knee_500_viewer.html").read_text())
    print(json.dumps({
        "motor_cavity_fit_pct":report["motor_inside_regenerated_nominal_thigh_cavity_pct"],
        "motor_thigh_plus_cuff_fit_pct":report["motor_inside_nominal_thigh_plus_cosmetic_cuff_cavity_pct"],
        "motor_vs_thigh_skin_mm3":report["motor_vs_unmodified_thigh_skin_mm3"],
        "motor_vs_cuff_skin_mm3":report["motor_vs_cosmetic_cuff_mm3"],
        "cuff_width_mm":report["scaled_500mm_cuff_lateral_width_mm"],
        "raw_max_shin_thigh_mm3":max(r["shin_vs_unmodified_thigh_mm3"] for r in raw),
        "raw_max_shin_motor_mm3":max(r["shin_vs_motor_mm3"] for r in raw),
        "raw_max_shin_cuff_mm3":max(r["shin_vs_original_cosmetic_cuff_mm3"] for r in raw),
    },indent=2),flush=True)


if __name__ == "__main__":
    main()
