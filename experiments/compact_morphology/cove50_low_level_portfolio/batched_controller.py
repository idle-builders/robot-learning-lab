"""Tensor-batched form of the saved four-actor command router.

This is a training interface, not a learned controller or an evaluation result.
Its state is per environment so a completed world can reset without erasing the
gait/action history of other worlds. Native parity is required before use.
"""

from __future__ import annotations

import torch


WALK = 0
STOP = 1
POSTURE = 2
ARMS = 3


class BatchedPortfolioRouter:
    def __init__(self, target_names: list[str], posture_action_scale: torch.Tensor,
                 num_envs: int, device: str):
        expected_legs = [f"{side}_{joint}" for side in ("left", "right") for joint in
                         ("hip_yaw", "hip_roll", "hip_pitch", "knee", "ankle_pitch")]
        if len(target_names) != 21 or target_names[:10] != expected_legs:
            raise ValueError("saved gait/posture target contract requires 21 joints and ten ordered legs")
        self.shoulders = [target_names.index(f"{side}_shoulder_pitch") for side in ("left", "right")]
        scale = torch.as_tensor(posture_action_scale, device=device, dtype=torch.float32)
        if scale.shape == (num_envs, 21):
            scale = scale[0]
        if scale.shape != (21,) or not bool(torch.all(scale[:10] > 0)):
            raise ValueError("invalid posture action scale")
        self.scale = scale
        self.num_envs = num_envs
        self.device = device
        self.last_gait_action = torch.zeros((num_envs, 21), device=device)
        self.previous_arm_flag = torch.zeros(num_envs, device=device)
        self.filtered = torch.zeros((num_envs, 21), device=device)
        self.has_filtered = torch.zeros(num_envs, dtype=torch.bool, device=device)

    @torch.no_grad()
    def reset(self, env_ids: torch.Tensor | None = None) -> None:
        ids = slice(None) if env_ids is None else env_ids
        self.last_gait_action[ids] = 0.0
        self.previous_arm_flag[ids] = 0.0
        self.filtered[ids] = 0.0
        self.has_filtered[ids] = False

    @torch.no_grad()
    def reset_where(self, done_mask: torch.Tensor) -> None:
        """Reset finished worlds without a per-step GPU-to-host synchronization."""
        if done_mask.shape != (self.num_envs,):
            raise ValueError("done mask needs one value per world")
        mask = done_mask.bool()
        self.last_gait_action.masked_fill_(mask[:, None], 0.0)
        self.previous_arm_flag.masked_fill_(mask, 0.0)
        self.filtered.masked_fill_(mask[:, None], 0.0)
        self.has_filtered.masked_fill_(mask, False)

    @torch.no_grad()
    def arm_observation(self, actor_obs: torch.Tensor) -> torch.Tensor:
        self._check(actor_obs, 72)
        out = actor_obs.clone()
        out[:, 69] = self.previous_arm_flag
        return out

    @torch.no_grad()
    def gait_observation(self, actor_obs: torch.Tensor, mode: torch.Tensor,
                         forward_m_s: torch.Tensor, yaw_rad_s: torch.Tensor) -> torch.Tensor:
        self._check(actor_obs, 72)
        self._check_modes(mode)
        out = actor_obs.clone()
        out[:, 48:69] = self.last_gait_action
        out[:, 69:72] = 0.0
        out[:, 69] = torch.where(mode == WALK, forward_m_s, 0.0)
        out[:, 71] = torch.where(mode == WALK, yaw_rad_s, 0.0)
        return out

    @torch.no_grad()
    def route(self, mode: torch.Tensor, squat_action: torch.Tensor,
              arm_action: torch.Tensor, gait_action: torch.Tensor,
              raise_arms: torch.Tensor) -> torch.Tensor:
        """Return one native 21-action row per world at the saved 50 Hz interface."""
        self._check_modes(mode)
        for value in (squat_action, arm_action, gait_action):
            self._check(value, 21)
        if raise_arms.shape != (self.num_envs,):
            raise ValueError("raise_arms must have one value per world")
        gait = (mode == WALK) | (mode == STOP)
        arms = mode == ARMS
        merged = squat_action.clamp(-1.0, 1.0).clone()
        merged[arms, :10] = 0.0
        for shoulder in self.shoulders:
            merged[arms, shoulder] = arm_action[arms, shoulder]
        merged[gait] = 0.0
        merged[gait, :10] = gait_action[gait, :10] * 0.3 / self.scale[:10]
        self.last_gait_action[gait] = gait_action[gait]
        replace = gait | ~self.has_filtered
        blended = 0.2 * merged + 0.8 * self.filtered
        self.filtered = torch.where(replace[:, None], merged, blended)
        self.has_filtered[:] = True
        self.previous_arm_flag[:] = raise_arms.float()
        return self.filtered.clone()

    def _check(self, value: torch.Tensor, width: int) -> None:
        if value.shape != (self.num_envs, width):
            raise ValueError(f"expected [{self.num_envs}, {width}], got {tuple(value.shape)}")

    def _check_modes(self, mode: torch.Tensor) -> None:
        # Modes are generated by the phase scheduler. Avoid a GPU-to-host
        # synchronization on every control step just to recheck their values.
        if mode.shape != (self.num_envs,):
            raise ValueError("one walk/stop/posture/arms mode is required per world")
